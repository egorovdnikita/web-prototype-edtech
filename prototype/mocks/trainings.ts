import type { Subject } from "./course";

// Интерактивные тренировки: 13 форматов, без ввода с клавиатуры,
// ошибка видна, но не блокирует, после решения — содержательное пояснение.
//
// Решение для телефона: ни один формат не опирается на наведение и перетаскивание.
// 13 форматов сводятся к 7 механикам на нажатиях — одним и тем же на любом экране:
// «нажми карточку → нажми место». Методист собирает тренировку из данных,
// механика — виджет каталога, её не рисуют под каждую тренировку.

export type Mechanic = "pick" | "match" | "slots" | "order" | "sort" | "fragments" | "map";

export type FormatId =
  | "match"
  | "memory"
  | "gaps"
  | "order"
  | "error"
  | "map-find"
  | "odd"
  | "clues"
  | "sort"
  | "chain"
  | "scheme"
  | "map-place"
  | "plan";

/** Каталог форматов → механика. `was` — на чём формат держался бы на десктопе:
 *  наведение или перетаскивание. */
