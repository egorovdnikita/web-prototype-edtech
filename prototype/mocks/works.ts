// Тест — задания 1 части, автопроверка по ключу и пояснения (B5).
// ДЗ — задания 2 части с критериями: на «С инструктором» проверяет куратор (B6),
// на «Фристайле» ученик оценивает себя сам (B7).

export type CheckMode = "auto" | "curator" | "self";

export interface Criterion {
  code: string;
  title: string;
  max: number;
  hint: string;
}

interface BaseTask {
  id: string;
  /** Номер задания ЕГЭ — для тренажёра и работы над ошибками. */
  ege: number;
  prompt: string;
}

/** Выбор нескольких вариантов: ответ — цифры по возрастанию, как в бланке ЕГЭ. */
export interface ChoiceTask extends BaseTask {
  type: "choice";
  options: string[];
  answer: string;
  explanation: string;
}

export interface ShortTask extends BaseTask {
  type: "short";
  answer: string;
  /** Другие засчитываемые формы ответа. */
  accept?: string[];
  explanation: string;
}

export interface LongTask extends BaseTask {
  type: "long";
  reference: string;
  criteria: Criterion[];
}

export type Task = ChoiceTask | ShortTask | LongTask;

export interface Work {
  check: CheckMode;
  /** Таймер по желанию ученика, минуты. */
  timer?: number;
  tasks: Task[];
}

export interface CuratorReview {
  reviewer: string;
  checkedAt: string;
  scores: Record<string, Record<string, number>>;
  comments: Record<string, string>;
}

