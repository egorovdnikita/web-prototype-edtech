export function maxScore(task: Task) {
  return task.type === "long" ? task.criteria.reduce((s, c) => s + c.max, 0) : 1;
}

const normalize = (s: string) => s.toLowerCase().replace(/ё/g, "е").replace(/[\s.,]+/g, " ").trim();

export function isCorrect(task: ChoiceTask | ShortTask, answer: string | undefined) {
  if (!answer) return false;
  if (task.type === "choice") return answer.split("").sort().join("") === task.answer;
  const given = normalize(answer);
  return [task.answer, ...(task.accept ?? [])].some((a) => normalize(a) === given);
}
